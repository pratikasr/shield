#!/usr/bin/env bash
# Copies the Foundry ABIs of the Shield contracts into the TypeScript packages.
#   keeper/src/abi/<Name>.ts and web/src/lib/abi/<Name>.ts: `export const <name>Abi = [...] as const`
#   indexer/abis/<Name>.json: the raw ABI array for Envio
# Run from anywhere after `forge build`: bash scripts/export-abi.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/contracts/out"
CONTRACTS=(PositionRegistry Repricer Executor ShieldVault ShieldForwarderFactory)

if [ ! -d "$OUT" ]; then
  echo "contracts/out not found; run 'cd contracts && forge build' first" >&2
  exit 1
fi

mkdir -p "$ROOT/keeper/src/abi" "$ROOT/web/src/lib/abi" "$ROOT/indexer/abis"

for name in "${CONTRACTS[@]}"; do
  artifact="$OUT/$name.sol/$name.json"
  if [ ! -f "$artifact" ]; then
    echo "missing $artifact; run 'cd contracts && forge build' first" >&2
    exit 1
  fi
  node -e '
    const fs = require("fs");
    const [artifact, name, keeperDir, webDir, indexerDir] = process.argv.slice(1);
    const abi = JSON.parse(fs.readFileSync(artifact, "utf8")).abi;
    const varName = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
    const ts = "// Generated by scripts/export-abi.sh from contracts/out. Do not edit.\n" +
      "export const " + varName + " = " + JSON.stringify(abi, null, 2) + " as const;\n";
    fs.writeFileSync(`${keeperDir}/${name}.ts`, ts);
    fs.writeFileSync(`${webDir}/${name}.ts`, ts);
    fs.writeFileSync(`${indexerDir}/${name}.json`, JSON.stringify(abi, null, 2) + "\n");
  ' "$artifact" "$name" "$ROOT/keeper/src/abi" "$ROOT/web/src/lib/abi" "$ROOT/indexer/abis"
  echo "exported $name"
done
